# ! Data Types In Python

#* ==> 1. Integer, Float, Complex, Boolean and String.
#* ==> 2. List(as Array), Tuples(Immutable), Set(Unique Values), Dictionary(Key-Value Pair).
#* ==> 3. Class

# ? String Data Types 

print("Hello, World") # Way 1
print('Hello, World') # Way 2
print("""Hello, World""") # Way 3

# ? Tuple Data Types
print((1, 2, 3, 4, 5)) # Way 1
print(tuple((1, 2, 3, 4, 5))) # Way 2

# ? Set Data Types
print({1, 2, 3, 4, 5}) # Way 1
print(set((1, 2, 3, 4, 5))) # Way 2

# ? Dictionary Data Types
print({"Name": "John", "Age": 30, "City": "New York"}) # Way 1
print(dict(Name="John", Age=30, City="New York")) # Way 2
